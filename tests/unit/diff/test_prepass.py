def test_write_diff_files(tmp_path, h) -> None:
    plan = prepass.plan(h.e1_files(), h.e1_patches(), h.make_cfg())
    index = prepass.write_diff_files(plan, tmp_path)
    mapping = json.loads(index.read_text(encoding="utf-8"))
    assert mapping == plan.per_file_diff_files
    svc = tmp_path / mapping["ledger/service.py"]
    assert svc.read_text(encoding="utf-8") == plan.diff_texts["ledger/service.py"]
    assert all(v.startswith("diffs/") and v.endswith(".txt") for v in mapping.values())


def test_incremental_files_recount_lines() -> None:
    files = [_file("src/a.py", 40, 2), _file("src/b.py", 5)]
    inc = {"src/a.py": _patch("src/a.py", 3)}
    out = prepass.incremental_files(files, inc, ["src/a.py"])
    assert [(f.path, f.additions, f.deletions) for f in out] == [("src/a.py", 3, 0)]
    plan = prepass.plan(out, inc, _cfg())
    assert plan.inlined == ["src/a.py"]


