def test_base_first_lines_reads_the_merge_base_version(make_repo, monkeypatch) -> None:
    base_tree = {
        "api/gen.py": _GEN + "\nX = 1\n",
        "api/old_pb2.py": _GEN + "\nY = 1\n",
        "src/app.py": "import os\n\nA = 1\n",
        "src/plain.py": "P = 1\n",
    }
    head_tree = {
        "api/gen.py": _GEN + "\nX = 2\n",
        "api/new_pb2.py": _GEN + "\nY = 2\n",  # renamed from api/old_pb2.py
        "api/added.py": _GEN + "\nZ = 1\n",
        "api/copy.py": _GEN + "\nX = 1\n",
        "src/app.py": "# @generated\nimport os\n\nA = 2\n",  # newly marked
        "src/plain.py": "P = 2\n",
    }
    repo, (base, _head) = make_repo(base_tree, head_tree)
    files = [
        _file("api/gen.py", 1, 1),
        _file("api/new_pb2.py", 1, 1, status="renamed", previous_path="api/old_pb2.py"),
        _file("api/added.py", 2, status="added"),
        _file("api/copy.py", 2, status="copied", previous_path="api/gen.py"),
        _file("src/app.py", 2, 1),
        _file("src/plain.py", 1, 1),
    ]
    heads = {p: "\n".join(t.splitlines()[:3]) for p, t in head_tree.items()}
    reads: list[str] = []
    real_show = prepass.show_file

    def counting_show(repo_dir: str, sha: str, path: str) -> str | None:
        reads.append(path)
        return real_show(repo_dir, sha, path)

    monkeypatch.setattr(prepass, "show_file", counting_show)
    got = prepass.base_first_lines(str(repo), base, files, heads)
    assert got == {
        "api/gen.py": _GEN + "\nX = 1",
        "api/new_pb2.py": _GEN + "\nY = 1",
        "src/app.py": "import os\n\nA = 1",
    }
    # Added and copied files have no base; src/plain.py has no head marker to check.
    assert sorted(reads) == ["api/gen.py", "api/old_pb2.py", "src/app.py"]

    patches = {f.path: _patch(f.path, 2) for f in files}
    plan = prepass.plan(files, patches, _cfg(), first_lines=heads, base_first_lines=got)
    assert {e.path: e.reason for e in plan.excluded} == {
        "api/gen.py": "generated",
        "api/new_pb2.py": "generated",
    }
    assert set(plan.reviewable) == {"api/added.py", "api/copy.py", "src/app.py", "src/plain.py"}


def test_base_first_lines_skips_unreadable_paths(make_repo) -> None:
    repo, (base,) = make_repo({"a.py": _GEN + "\n"})
    files = [_file("missing.py", 1, 1), _file("a.py", 1, 1)]
    assert prepass.base_first_lines(str(repo), base, files) == {"a.py": _GEN}
    # An invalid sha is a git error: the file stays out (reviewable), nothing raises.
    assert prepass.base_first_lines(str(repo), "not-a-sha", files) == {}
