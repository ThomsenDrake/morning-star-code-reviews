def _file(path: str, add: int = 1, dele: int = 0, **kw) -> PrFile:
    status = kw.pop("status", "modified")
    return PrFile(path=path, status=status, additions=add, deletions=dele, has_patch=True, **kw)


def _patch(path: str, n: int, width: int = 10, status: str = "modified") -> FilePatch:
    body = "\n".join("+" + "x" * width for _ in range(n))
    return parse_patch(path, f"@@ -0,0 +1,{n} @@\n{body}", status, None)


