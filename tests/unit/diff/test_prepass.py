def test_e1_plan_excludes_artifacts(h) -> None:
    plan = prepass.plan(h.e1_files(), h.e1_patches(), h.make_cfg())
    excluded = {e.path: e.reason for e in plan.excluded}
    assert excluded == {"assets/logo.png": "binary", "uv.lock": "lock_file"}
    assert set(plan.inlined) == {
        "ledger/service.py",
        "ledger/handlers.py",
        "ledger/db.py",
        "ledger/util.py",
        "ledger/VERSION",
        "ledger/legacy.py",
        "notes.txt",
    }
    assert plan.on_demand == [] and plan.partial_reason is None
    # Excluded files with a diff are still served by show_file_diff.
    assert "uv.lock" in plan.per_file_diff_files
    assert plan.rendered_diff.startswith("=== ledger/service.py (modified)")


def test_repo_config_excludes_and_generated_marker(h) -> None:
    cfg = h.make_cfg(exclude=["ledger/util.py"])
    files = [*h.e1_files(), _file("api/gen.py", 3)]
    patches = {**h.e1_patches(), "api/gen.py": _patch("api/gen.py", 3)}
    plan = prepass.plan(
        files, patches, cfg, first_lines={"api/gen.py": "# Code generated. DO NOT EDIT."}
    )
    reasons = {e.path: e.reason for e in plan.excluded}
    assert reasons["ledger/util.py"] == "repository_config: ledger/util.py"
    assert reasons["api/gen.py"] == "generated"


def test_generated_marker_read_from_patch_when_it_starts_at_line_one() -> None:
    patch = parse_patch(
        "g.go", "@@ -0,0 +1,2 @@\n+// @generated by protoc\n+package g", "added", None
    )
    plan = prepass.plan([_file("g.go", 2, status="added")], {"g.go": patch}, _cfg())
    assert [e.reason for e in plan.excluded] == ["generated"]


def _cfg(**budgets):
    from morning_star_review.core.contract import ResolvedConfig, ResolvedRoles

    roles = ResolvedRoles(
        explorer_model="zai-glm-5-3",
        explorer_effort="high",
        formatter_model="mistral-large-4",
        formatter_effort="low",
    )
    return ResolvedConfig(roles=roles, budgets=ResolvedBudgets(**budgets))


def test_ranking_weights() -> None:
    w = prepass.kind_weight
    assert w("src/app.py") == 1.0
    assert w("deploy/config.yaml") == 0.8 and w("Dockerfile") == 0.8 and w("db/q.sql") == 0.8
    assert w("tests/test_app.py") == 0.6 and w("web/a.spec.ts") == 0.6 and w("pkg/x_test.go") == 0.6
    assert w("vendor/lib.go") == 0.2 and w("build/out.js") == 0.2
    assert w("docs/guide.rst") == 0.2 and w("README.md") == 0.2
    assert w("src/app.py", deletion_only=True) == 0.3
    src = prepass.rank_score(_file("src/app.py", 10))
    risky = prepass.rank_score(_file("src/auth/session.py", 10))
    assert risky == pytest.approx(src * 1.5)
    assert prepass.rank_score(_file("tests/test_a.py", 10)) < src


def test_rank_order_and_budget_clipping() -> None:
    files = [_file("docs/a.md", 50), _file("src/core.py", 50), _file("tests/test_core.py", 50)]
    patches = {f.path: _patch(f.path, 50) for f in files}
    size = len(render_file(patches["src/core.py"])) + 1
    budget = size * 2 + 20  # room for two files (headers differ by a few chars), not three
    plan = prepass.plan(files, patches, _cfg(inline_diff_chars=budget, max_file_share=1.0))
    assert plan.ranked == ["src/core.py", "tests/test_core.py", "docs/a.md"]
    assert plan.inlined == ["src/core.py", "tests/test_core.py"]
    assert plan.on_demand == ["docs/a.md"]
    assert len(plan.rendered_diff) <= budget


def test_max_file_share_sends_big_files_on_demand() -> None:
    files = [_file("src/big.py", 400), _file("src/small.py", 5)]
    patches = {"src/big.py": _patch("src/big.py", 400), "src/small.py": _patch("src/small.py", 5)}
    plan = prepass.plan(files, patches, _cfg(inline_diff_chars=10_000, max_file_share=0.4))
    assert plan.inlined == ["src/small.py"]
    assert plan.on_demand == ["src/big.py"]


def test_zero_budget_inlines_nothing() -> None:
    files = [_file("src/a.py", 3)]
    plan = prepass.plan(files, {"src/a.py": _patch("src/a.py", 3)}, _cfg(inline_diff_chars=0))
    assert plan.inlined == [] and plan.on_demand == ["src/a.py"] and plan.rendered_diff == ""


def test_hard_ceiling_on_changed_lines() -> None:
    files = [_file(f"src/m{i}.py", 6000) for i in range(5)]
    plan = prepass.plan(files, {}, _cfg())
    kept = plan.inlined + plan.on_demand
    assert len(kept) == 3  # 18,000 lines fit under 20,000
    over = [e for e in plan.excluded if e.reason == "over_ceiling"]
    assert len(over) == 2
    assert plan.partial_reason and "20000" in plan.partial_reason
    # No patch available: the file is still reviewable, with a stand-in text.
    assert "diff not available" in plan.diff_texts[kept[0]]


def test_partial_when_github_lists_fewer_files() -> None:
    files = [_file("src/a.py", 1)]
    plan = prepass.plan(files, {"src/a.py": _patch("src/a.py", 1)}, _cfg(), total_files=3500)
    assert plan.partial_reason and "3500" in plan.partial_reason


def test_pure_rename_is_not_reviewable() -> None:
    f = PrFile(
        path="b.py",
        previous_path="a.py",
        status="renamed",
        additions=0,
        deletions=0,
        has_patch=False,
    )
    plan = prepass.plan([f], {}, _cfg())
    assert [(e.path, e.reason) for e in plan.excluded] == [("b.py", "no_line_changes")]


def test_binary_without_patch_is_excluded() -> None:
    f = PrFile(path="img/a.webp", status="added", additions=0, deletions=0, has_patch=False)
    plan = prepass.plan([f], {}, _cfg())
    assert plan.excluded[0].reason == "binary"


def test_write_diff_files(tmp_path, h) -> None:
    plan = prepass.plan(h.e1_files(), h.e1_patches(), h.make_cfg())
    index = prepass.write_diff_files(plan, tmp_path)
    mapping = json.loads(index.read_text(encoding="utf-8"))
    assert mapping == plan.per_file_diff_files
    svc = tmp_path / mapping["ledger/service.py"]
    assert svc.read_text(encoding="utf-8") == plan.diff_texts["ledger/service.py"]
    assert all(v.startswith("diffs/") and v.endswith(".txt") for v in mapping.values())


def test_incremental_files_recount_lines() -> None:
    files = [_file("src/a.py", 40, 2), _file("src/b.py", 5)]
    inc = {"src/a.py": _patch("src/a.py", 3)}
    out = prepass.incremental_files(files, inc, ["src/a.py"])
    assert [(f.path, f.additions, f.deletions) for f in out] == [("src/a.py", 3, 0)]
    plan = prepass.plan(out, inc, _cfg())
    assert plan.inlined == ["src/a.py"]
