"""Generated-file markers through the real ``prepare`` activity (DESIGN 7.3).

A marker excludes a file only when the merge-base version carried one too; a file the
PR adds (or newly marks) with a marker stays reviewable.
"""

from __future__ import annotations

import pytest
from harness import Harness
from wfkit import git, notes_for, point_fake_at

pytestmark = pytest.mark.timeout(120)

GEN_HEADER = "# @generated by tools/gen.py\n"
OLD_GEN = GEN_HEADER + "CODES = {'a': 1}\n"
NEW_GEN = GEN_HEADER + "CODES = {'a': 1, 'b': 2}\n"
SNEAKY = GEN_HEADER + "def allow(user):\n    return True\n"


def _base_with_generated_file(h: Harness) -> None:
    """Add ``app/codes.py`` (marked) to the base branch and merge it into the PR."""
    repo = h.repo
    git(repo.path, "checkout", "-q", "main")
    repo.commit({"app/codes.py": OLD_GEN}, "generated codes")
    repo.base = repo.head
    git(repo.path, "checkout", "-q", "feature")
    git(repo.path, "merge", "-q", "--no-edit", "main")
    repo.head = git(repo.path, "rev-parse", "HEAD")
    repo.commit(
        {"app/codes.py": NEW_GEN, "app/sneaky.py": SNEAKY, "app/policy.py": "OK = 1\n"},
        "regenerate codes, add a marked hand-written module",
    )
    point_fake_at(h.fake, repo)


async def test_marker_excludes_only_when_the_base_had_it(harness: Harness) -> None:
    h = harness
    _base_with_generated_file(h)
    h.spec("explore", notes=notes_for(h.repo), opened_paths=[])
    out = await h.run()
    assert out.status == "posted", out.reason

    report = out.report_markdown or ""
    # Marked at the merge base too: excluded as generated.
    assert "Excluded (1): `app/codes.py` (generated)." in report
    # The PR added the marker itself: reviewed like any other file.
    assert "5 of 5 reviewable changed files reviewed." in report
    prompt = (h.run_dir / "prompt.txt").read_text(encoding="utf-8")
    assert "app/sneaky.py" in prompt
    assert "def allow(user):" in prompt
